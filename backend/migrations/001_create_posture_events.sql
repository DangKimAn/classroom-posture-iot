CREATE TABLE IF NOT EXISTS posture_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL UNIQUE,
    ts TIMESTAMPTZ NOT NULL,
    seat_id TEXT NOT NULL,
    label TEXT NOT NULL CHECK (label IN ('upright', 'slouching', 'leaning', 'unknown')),
    trunk_angle REAL,
    confidence REAL NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
    model_version TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_posture_events_ts ON posture_events(ts);
CREATE INDEX IF NOT EXISTS idx_posture_events_seat_ts ON posture_events(seat_id, ts);
